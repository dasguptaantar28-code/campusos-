/**
 * CampusOS — Automated Supabase Connection & Configuration Script
 * Usage:
 *   node scripts/connect_supabase.js <SUPABASE_URL> <ANON_KEY> [SERVICE_ROLE_KEY]
 */

const fs = require('fs');
const path = require('path');
const https = require('https');

const rootDir = path.resolve(__dirname, '..');
const webEnvPath = path.join(rootDir, 'apps', 'web', '.env.local');
const rootEnvPath = path.join(rootDir, '.env');
const gradlePropsPath = path.join(rootDir, 'apps', 'mobile-android', 'gradle.properties');

const [,, inputUrl, inputAnonKey, inputServiceKey] = process.argv;

if (!inputUrl || !inputAnonKey) {
  console.log('---------------------------------------------------------');
  console.log('CampusOS — Supabase Connector');
  console.log('---------------------------------------------------------');
  console.log('Usage: node scripts/connect_supabase.js <SUPABASE_URL> <ANON_KEY> [SERVICE_ROLE_KEY]');
  console.log('Example:');
  console.log('  node scripts/connect_supabase.js https://xyz.supabase.co eyJhbG... eyJhbG...');
  process.exit(1);
}

const supabaseUrl = inputUrl.trim().replace(/\/+$/, '');
const anonKey = inputAnonKey.trim();
const serviceKey = (inputServiceKey || '').trim();

console.log(`[1/3] Testing connection to ${supabaseUrl}...`);

const checkUrl = new URL(`${supabaseUrl}/auth/v1/health`);
const req = https.get(checkUrl, {
  headers: {
    'apikey': anonKey
  },
  timeout: 8000
}, (res) => {
  console.log(`[✓] Supabase Auth endpoint responded with status code: ${res.statusCode}`);

  // 1. Write apps/web/.env.local
  const envContent = [
    '# CampusOS Web Environment Configuration',
    '# Auto-generated by connect_supabase.js',
    'NEXT_PUBLIC_APP_NAME=CampusOS',
    'NEXT_PUBLIC_APP_URL=http://localhost:3000',
    `NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    `NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY=${anonKey}`,
    serviceKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}` : '# SUPABASE_SERVICE_ROLE_KEY=',
    ''
  ].join('\n');

  fs.writeFileSync(webEnvPath, envContent, 'utf8');
  fs.writeFileSync(rootEnvPath, envContent, 'utf8');
  console.log(`[2/3] Saved configuration to apps/web/.env.local and .env`);

  // 2. Update Android gradle.properties with the keys for building
  let gradleProps = '';
  if (fs.existsSync(gradlePropsPath)) {
    gradleProps = fs.readFileSync(gradlePropsPath, 'utf8');
  }
  gradleProps = gradleProps
    .replace(/^SUPABASE_URL=.*$/m, '')
    .replace(/^SUPABASE_ANON_KEY=.*$/m, '')
    .trim();

  gradleProps += `\nSUPABASE_URL=${supabaseUrl}\nSUPABASE_ANON_KEY=${anonKey}\n`;
  fs.writeFileSync(gradlePropsPath, gradleProps, 'utf8');
  console.log(`[3/3] Updated apps/mobile-android/gradle.properties for APK build`);

  console.log('\n=========================================================');
  console.log(' SUCCESS: Supabase credentials successfully connected!');
  console.log(' Database Schema: Execute supabase/full_schema.sql in your');
  console.log(' Supabase Dashboard -> SQL Editor to initialize all 70+ tables.');
  console.log('=========================================================\n');
  process.exit(0);
});

req.on('error', (err) => {
  console.error(`[!] Warning: Could not reach ${supabaseUrl}:`, err.message);
  console.log('Saving environment files anyway...');

  const envContent = [
    'NEXT_PUBLIC_APP_NAME=CampusOS',
    'NEXT_PUBLIC_APP_URL=http://localhost:3000',
    `NEXT_PUBLIC_SUPABASE_URL=${supabaseUrl}`,
    `NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}`,
    serviceKey ? `SUPABASE_SERVICE_ROLE_KEY=${serviceKey}` : '',
    ''
  ].join('\n');
  fs.writeFileSync(webEnvPath, envContent, 'utf8');
  fs.writeFileSync(rootEnvPath, envContent, 'utf8');
  console.log(`Saved apps/web/.env.local and .env`);
  process.exit(0);
});
